# typed: true
# frozen_string_literal: true

require "spec_helper"
require "dependabot/python"

RSpec.describe Dependabot::Python::PipCompileFileMatcher do
  subject(:matcher) { described_class.new(requirements_in_files) }

  let(:requirements_in_file) do
    Dependabot::DependencyFile.new(
      name: "requirements.in",
      content: "requests==2.32.5\n",
      directory: "/"
    )
  end

  let(:requirements_in_files) { [requirements_in_file] }

  describe "#manifest_for_pip_compile_lockfile" do
    context "when lockfile has a matching .in basename" do
      let(:lockfile) do
        Dependabot::DependencyFile.new(
          name: "requirements.txt",
          content: "requests==2.32.5\n",
          directory: "/"
        )
      end

      it "returns the matching manifest file" do
        expect(matcher.manifest_for_pip_compile_lockfile(lockfile)).to eq(requirements_in_file)
      end
    end

    context "when lockfile has no matching .in basename" do
      let(:other_manifest) do
        Dependabot::DependencyFile.new(
          name: "base.in",
          content: "requests==2.32.5\n",
          directory: "/"
        )
      end

      let(:requirements_in_files) { [other_manifest] }

      let(:lockfile) do
        Dependabot::DependencyFile.new(
          name: "requirements.txt",
          content: <<~TXT,
            # This file is autogenerated by pip-compile
            #    pip-compile --output-file=requirements.txt pyproject.toml
            requests==2.32.5
          TXT
          directory: "/"
        )
      end

      it "returns nil rather than guessing" do
        expect(matcher.manifest_for_pip_compile_lockfile(lockfile)).to be_nil
      end

      context "when the compile command names a different manifest" do
        let(:dev_manifest) do
          Dependabot::DependencyFile.new(name: "dev.in", content: "pytest\n", directory: "/")
        end

        let(:requirements_in_files) { [other_manifest, dev_manifest] }

        let(:lockfile) do
          Dependabot::DependencyFile.new(
            name: "constraints.txt",
            content: <<~TXT,
              # This file is autogenerated by pip-compile
              #    pip-compile --output-file=constraints.txt dev.in
              pytest==8.3.3
            TXT
            directory: "/"
          )
        end

        it "returns the manifest named in the compile command" do
          expect(matcher.manifest_for_pip_compile_lockfile(lockfile)).to eq(dev_manifest)
        end

        it "ignores .in files passed as constraints or overrides" do
          ["--constraint=base.in", "-c base.in", "--override base.in"].each do |option|
            output = Dependabot::DependencyFile.new(
              name: "constraints.txt",
              content: "#    pip-compile #{option} --output-file=constraints.txt dev.in\npytest==8.3.3\n",
              directory: "/"
            )

            expect(matcher.manifest_for_pip_compile_lockfile(output)).to eq(dev_manifest), option
          end
        end
      end
    end

    context "when file is not a pip-compile lockfile" do
      let(:lockfile) do
        Dependabot::DependencyFile.new(
          name: "Pipfile.lock",
          content: "{}",
          directory: "/"
        )
      end

      it "returns nil" do
        expect(matcher.manifest_for_pip_compile_lockfile(lockfile)).to be_nil
      end
    end
  end
end
